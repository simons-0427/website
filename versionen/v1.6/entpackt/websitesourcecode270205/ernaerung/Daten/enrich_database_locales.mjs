function translateName(name) {
  let out = String(name).trim();
  if (exactTranslations.has(out)) return exactTranslations.get(out);
  for (const [from, to] of [...compoundTranslations].sort((a, b) => b[0].length - a[0].length)) {
    out = replacePhrase(out, from, to);
  }
  for (const [from, to] of [...phraseTranslations].sort((a, b) => b[0].length - a[0].length)) {
    out = /[^\p{L}\s'-]/u.test(from) || /\s/u.test(from)
      ? replacePhrase(out, from, to)
      : replaceWord(out, from, to);
  }
  for (const [from, to] of [...wordTranslations].sort((a, b) => b[0].length - a[0].length)) {
    out = /[^\p{L}\s'-]/u.test(from) || /\s/u.test(from)
      ? replacePhrase(out, from, to)
      : replaceWord(out, from, to);
  }
  out = out
    .replace(/\braw,?/giu, "raw")
    .replace(/\bthe (raw|dry|fresh|cooked|baked|grilled|steamed)/giu, "$1")
    .replace(/\s*,\s*/g, ", ")
    .replace(/\s*\/\s*/g, " / ")
    .replace(/\s+/g, " ")
    .replace(/\(\s+/g, "(")
    .replace(/\s+\)/g, ")")
    .replace(/,\s*\)/g, ")")
    .trim();
  return out.charAt(0).toUpperCase() + out.slice(1);
}

