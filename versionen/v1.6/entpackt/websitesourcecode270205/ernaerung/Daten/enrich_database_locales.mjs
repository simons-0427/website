function priceFactor(food, market) {
  const text = `${food.name} ${food.category}`;
  for (const [pattern, uk, us, label] of factorRules) {
    if (pattern.test(text)) return { factor: market === "uk" ? uk : us, label };
  }
  const fallback = categoryFactors[food.category] || [1, 1];
  return { factor: market === "uk" ? fallback[0] : fallback[1], label: `category:${food.category}` };
}

function roundPrice(value) {
  if (value < 0.01) return Number(value.toFixed(6));
  if (value < 0.1) return Number(value.toFixed(4));
  return Number(value.toFixed(3));
}

function localizedPrice(food, market) {
  const base = Number(food.price_per_100);
  if (!Number.isFinite(base) || base < 0) throw new Error(`Invalid base price for ${food.name}`);
  const { factor } = priceFactor(food, market);
  return roundPrice(base * factor * SURCHARGE);
}

